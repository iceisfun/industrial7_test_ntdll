#!/usr/bin/env python3
"""Generate resolve-only reference metadata; no undocumented export is invoked."""
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
items = json.loads((root / 'tools/ntdll_exports.json').read_text())
lines = ['/* Generated by tools/generate_export_table.py from the Win10 export manifest. */',
         'static const struct { const char *name; unsigned ordinal; DWORD rva; } reference_exports[] = {']
for entry in items:
    name = json.dumps(entry['name']) if entry['name'] else 'NULL'
    lines.append('    {%s, %d, 0x%x},' % (name, entry['ordinal'], entry['rva']))
lines.append('};')
(root / 'tests/export_surface/reference.inc').write_text('\n'.join(lines) + '\n')
